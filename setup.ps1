# PyForge Studio - Windows Setup Script
# Run once from the project root: .\setup.ps1
# Creates .venv, installs all dependencies, then prints how to launch.

#Requires -Version 5.1
$ErrorActionPreference = "Stop"

# -- Helpers -------------------------------------------------------------------
function Write-Step { param($msg) Write-Host "`n>> $msg" -ForegroundColor Cyan   }
function Write-Ok   { param($msg) Write-Host "   $msg"  -ForegroundColor Green  }
function Write-Warn { param($msg) Write-Host "   $msg"  -ForegroundColor Yellow }
function Write-Fail { param($msg) Write-Host "   $msg"  -ForegroundColor Red; exit 1 }

# Invoke a native exe and stop the script if it exits non-zero.
function Invoke-Checked {
    & $args[0] $args[1..($args.Length-1)]
    if ($LASTEXITCODE -ne 0) {
        Write-Fail "Command failed (exit $LASTEXITCODE): $($args -join ' ')"
    }
}

Write-Host ""
Write-Host "  PyForge Studio - Windows Setup" -ForegroundColor Magenta
Write-Host "  --------------------------------"

# -- 1. Locate Python ----------------------------------------------------------
Write-Step "Checking Python..."

$python = $null
foreach ($candidate in @("python", "python3", "py")) {
    try {
        $ver = & $candidate -c "import sys; print(f'{sys.version_info.major}.{sys.version_info.minor}')" 2>$null
        if ($ver) { $python = $candidate; break }
    } catch {}
}

if (-not $python) {
    Write-Fail "Python not found. Install Python 3.10+ from https://python.org and add it to PATH."
}

$verParts = $ver.Split(".")
if ([int]$verParts[0] -lt 3 -or ([int]$verParts[0] -eq 3 -and [int]$verParts[1] -lt 10)) {
    Write-Fail "Python $ver found, but 3.10+ is required."
}
Write-Ok "Python $ver - OK"

# -- 2. Create virtual environment ---------------------------------------------
Write-Step "Setting up virtual environment..."

$venvDir = ".venv"
if (Test-Path "$venvDir\Scripts\python.exe") {
    Write-Ok "Existing venv found at $venvDir - reusing."
} else {
    & $python -m venv $venvDir
    Write-Ok "Created $venvDir"
}

$pip   = "$venvDir\Scripts\pip.exe"
$venvPy = "$venvDir\Scripts\python.exe"

# -- 3. Core UI dependencies ---------------------------------------------------
Write-Step "Installing UI dependencies (customtkinter, Pillow)..."
Invoke-Checked $pip install --upgrade pip --quiet
Invoke-Checked $pip install "customtkinter>=5.2.0" "Pillow>=10.0.0" --quiet
Write-Ok "Done."

# -- 4. PyTorch ----------------------------------------------------------------
Write-Step "Installing PyTorch..."
Write-Warn "Default: CUDA 12.4 (supports Python 3.10-3.13).  Edit TORCH_INDEX_URL below to change:"
Write-Warn "  CPU-only:  https://download.pytorch.org/whl/cpu"
Write-Warn "  CUDA 11.8: https://download.pytorch.org/whl/cu118"
Write-Warn "  CUDA 12.1: https://download.pytorch.org/whl/cu121"

$TORCH_INDEX_URL = "https://download.pytorch.org/whl/cu124"
Invoke-Checked $pip install torch torchvision --index-url $TORCH_INDEX_URL --quiet
Write-Ok "PyTorch installed."

# -- 5. AI / diffusion dependencies --------------------------------------------
Write-Step "Installing AI dependencies (diffusers, transformers, huggingface_hub)..."
Invoke-Checked $pip install diffusers transformers huggingface_hub accelerate --quiet
Write-Ok "Done."

# -- 6. Optional: xFormers (VRAM saver) ----------------------------------------
Write-Warn ""
Write-Warn "Optional: xFormers (reduces VRAM usage).  Uncomment to install:"
Write-Warn '  & $pip install xformers'

# -- 7. Write launcher ---------------------------------------------------------
Write-Step "Creating launcher..."

$batLines = @(
    '@echo off',
    ':: PyForge Studio launcher - generated by setup.ps1',
    'cd /d "%~dp0"',
    'if not exist ".venv\Scripts\python.exe" (',
    '    echo ERROR: .venv not found.  Run setup.ps1 first.',
    '    pause',
    '    exit /b 1',
    ')',
    '".venv\Scripts\python.exe" run.py %*'
)
$batLines | Set-Content -Path "PyForgeStudio.bat" -Encoding ASCII
Write-Ok "PyForgeStudio.bat written."

# -- Done ----------------------------------------------------------------------
Write-Host ""
Write-Host "  Setup complete!" -ForegroundColor Green
Write-Host ""
Write-Host "  To run PyForge Studio:"
Write-Host "    Double-click  PyForgeStudio.bat"
Write-Host "    - or -"
Write-Host "    .\.venv\Scripts\python.exe run.py"
Write-Host ""
