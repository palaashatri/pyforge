#!/usr/bin/env bash
# PyForge Studio — macOS / Linux Setup Script
# Run once from the project root: bash setup.sh
# Creates .venv, installs all dependencies, then prints how to launch.

set -euo pipefail

# ── Helpers ───────────────────────────────────────────────────────────────────
step()  { echo; echo ">> $*"; }
ok()    { echo "   ✓ $*"; }
warn()  { echo "   ! $*"; }
fail()  { echo "   ✗ $*" >&2; exit 1; }

echo ""
echo "  ◆  PyForge Studio — Setup"
echo "  ─────────────────────────"

# ── 1. Detect OS ──────────────────────────────────────────────────────────────
OS="$(uname -s)"
ARCH="$(uname -m)"

if [[ "$OS" == "Darwin" ]]; then
    PLATFORM="macos"
elif [[ "$OS" == "Linux" ]]; then
    PLATFORM="linux"
else
    fail "Unsupported OS: $OS"
fi
ok "Platform: $PLATFORM ($ARCH)"

# ── 2. Locate Python 3.10+ ────────────────────────────────────────────────────
step "Checking Python..."

PYTHON=""
for candidate in python3.12 python3.11 python3.10 python3 python; do
    if command -v "$candidate" &>/dev/null; then
        ver=$("$candidate" -c "import sys; print(f'{sys.version_info.major}.{sys.version_info.minor}')" 2>/dev/null || true)
        major="${ver%%.*}"
        minor="${ver##*.}"
        if [[ "$major" -ge 3 && "$minor" -ge 10 ]]; then
            PYTHON="$candidate"
            break
        fi
    fi
done

if [[ -z "$PYTHON" ]]; then
    if [[ "$PLATFORM" == "macos" ]]; then
        fail "Python 3.10+ not found. Install with: brew install python@3.12"
    else
        fail "Python 3.10+ not found. Install with: sudo apt install python3.12 python3.12-venv"
    fi
fi

ok "Python $ver at $(command -v "$PYTHON")"

# ── 3. Create virtual environment ─────────────────────────────────────────────
step "Setting up virtual environment..."

VENV=".venv"
if [[ -f "$VENV/bin/python" ]]; then
    ok "Existing venv found at $VENV — reusing."
else
    "$PYTHON" -m venv "$VENV"
    ok "Created $VENV"
fi

PIP="$VENV/bin/pip"
VENV_PY="$VENV/bin/python"

# ── 4. Core UI dependencies ───────────────────────────────────────────────────
step "Installing UI dependencies (customtkinter, Pillow)..."
"$PIP" install --upgrade pip --quiet
"$PIP" install "customtkinter>=5.2.0" "Pillow>=10.0.0" --quiet
ok "Done."

# ── 5. PyTorch ────────────────────────────────────────────────────────────────
step "Installing PyTorch..."

if [[ "$PLATFORM" == "macos" ]]; then
    if [[ "$ARCH" == "arm64" ]]; then
        warn "Apple Silicon detected — installing torch with MPS support."
        "$PIP" install torch torchvision --quiet
    else
        warn "Intel Mac detected — installing CPU-only torch."
        "$PIP" install torch torchvision --quiet
    fi
else
    # Linux — default to CUDA 12.1; edit if needed
    warn "Linux: defaulting to CUDA 12.1 torch."
    warn "  CPU-only:  pip install torch torchvision --index-url https://download.pytorch.org/whl/cpu"
    warn "  CUDA 11.8: pip install torch torchvision --index-url https://download.pytorch.org/whl/cu118"
    "$PIP" install torch torchvision \
        --index-url https://download.pytorch.org/whl/cu121 --quiet
fi
ok "PyTorch installed."

# ── 6. AI / diffusion dependencies ────────────────────────────────────────────
step "Installing AI dependencies (diffusers, transformers, huggingface_hub)..."
"$PIP" install diffusers transformers huggingface_hub accelerate --quiet
ok "Done."

# ── 7. Optional: xFormers ────────────────────────────────────────────────────
warn ""
warn "Optional: xFormers (reduces VRAM usage on NVIDIA GPUs)"
warn "  $PIP install xformers"

# ── 8. Write launcher ─────────────────────────────────────────────────────────
step "Writing launcher..."

LAUNCHER="run_pyforge.sh"
cat > "$LAUNCHER" <<'LAUNCH'
#!/usr/bin/env bash
# PyForge Studio launcher — generated by setup.sh
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VENV_PY="$SCRIPT_DIR/.venv/bin/python"
if [[ ! -x "$VENV_PY" ]]; then
    echo "ERROR: .venv not found. Run setup.sh first." >&2
    exit 1
fi
exec "$VENV_PY" "$SCRIPT_DIR/run.py" "$@"
LAUNCH
chmod +x "$LAUNCHER"
ok "$LAUNCHER written."

# macOS: also write a double-clickable .command file
if [[ "$PLATFORM" == "macos" ]]; then
    COMMAND_FILE="PyForgeStudio.command"
    cat > "$COMMAND_FILE" <<CMDEOF
#!/usr/bin/env bash
cd "\$(dirname "\$0")"
./.venv/bin/python run.py
CMDEOF
    chmod +x "$COMMAND_FILE"
    ok "$COMMAND_FILE written (double-clickable in Finder)."
fi

# ── Done ──────────────────────────────────────────────────────────────────────
echo ""
echo "  Setup complete!"
echo ""
echo "  To run PyForge Studio:"
if [[ "$PLATFORM" == "macos" ]]; then
    echo "    Double-click  PyForgeStudio.command"
    echo "    — or —"
fi
echo "    bash run_pyforge.sh"
echo "    — or —"
echo "    ./.venv/bin/python run.py"
echo ""
